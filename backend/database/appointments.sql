BEGIN;

CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    customer_name VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(30) NOT NULL,
    service_name VARCHAR(150) NOT NULL,
    employee_id BIGINT,
    appointment_date DATE NOT NULL,
    appointment_time TIME NOT NULL,
    notes TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT appointments_employee_same_tenant
        FOREIGN KEY (tenant_id, employee_id)
        REFERENCES public.users (tenant_id, id)
);

CREATE INDEX IF NOT EXISTS appointments_tenant_date_idx
ON public.appointments (tenant_id, appointment_date, appointment_time);

ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS appointments_tenant_isolation
ON public.appointments;

CREATE POLICY appointments_tenant_isolation
ON public.appointments
FOR ALL
TO public
USING (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
)
WITH CHECK (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
);

GRANT SELECT, INSERT, UPDATE
ON public.appointments TO barberpro_app;

GRANT USAGE, SELECT
ON SEQUENCE public.appointments_id_seq TO barberpro_app;

COMMIT;
