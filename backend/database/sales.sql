BEGIN;

CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    tenant_id BIGINT NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    appointment_id BIGINT REFERENCES public.appointments(id) ON DELETE SET NULL,
    employee_id BIGINT,
    created_by BIGINT NOT NULL REFERENCES public.users(id),
    customer_name VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(30),
    payment_method VARCHAR(20) NOT NULL
        CHECK (payment_method IN ('cash', 'card', 'wallet', 'other')),
    subtotal NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    total NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'completed'
        CHECK (status IN ('completed', 'refunded')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT sales_employee_same_tenant
        FOREIGN KEY (tenant_id, employee_id)
        REFERENCES public.users (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS public.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    sale_id BIGINT NOT NULL REFERENCES public.sales(id) ON DELETE CASCADE,
    service_id BIGINT REFERENCES public.services(id) ON DELETE SET NULL,
    service_name VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(10,2) NOT NULL CHECK (line_total >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sales_tenant_created_idx
ON public.sales (tenant_id, created_at DESC);

CREATE INDEX IF NOT EXISTS sales_tenant_invoice_idx
ON public.sales (tenant_id, invoice_number);

CREATE INDEX IF NOT EXISTS sale_items_tenant_sale_idx
ON public.sale_items (tenant_id, sale_id);

ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS sales_tenant_isolation ON public.sales;

CREATE POLICY sales_tenant_isolation
ON public.sales
FOR ALL TO public
USING (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
)
WITH CHECK (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
);

ALTER TABLE public.sale_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sale_items FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS sale_items_tenant_isolation ON public.sale_items;

CREATE POLICY sale_items_tenant_isolation
ON public.sale_items
FOR ALL TO public
USING (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
)
WITH CHECK (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::BIGINT
);

GRANT SELECT, INSERT, UPDATE ON public.sales TO barberpro_app;
GRANT USAGE, SELECT ON SEQUENCE public.sales_id_seq TO barberpro_app;
GRANT USAGE, SELECT ON SEQUENCE public.sales_invoice_number_seq TO barberpro_app;

GRANT SELECT, INSERT ON public.sale_items TO barberpro_app;
GRANT USAGE, SELECT ON SEQUENCE public.sale_items_id_seq TO barberpro_app;

COMMIT;
